def xml_line(x, y, line, size=12.5):
    indent = len(line) - len(line.lstrip(' '))
    tspans = []
    for token in re.findall(r'</?|/?>|[A-Za-z_]+="[^"]*"|[A-Za-z_]+|\s+|.', line.lstrip(' ')):
        if token in ('<', '</', '>', '/>'):
            tspans.append(f'<tspan fill="#A69CB8">{escape(token)}</tspan>')
        elif '="' in token:
            name, value = token.split('=', 1)
            tspans.append(f'<tspan fill="{MUTED}">{name}=</tspan><tspan fill="#A23B80">{escape(value)}</tspan>')
        elif token.strip():
            tspans.append(f'<tspan fill="{P700}" font-weight="600">{escape(token)}</tspan>')
        else:
            tspans.append(token)
    add(f'<text x="{x}" y="{y}" font-family="{MONO}" font-size="{size}" xml:space="preserve">{" " * indent}{"".join(tspans)}</text>')


